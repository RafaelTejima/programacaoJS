let celsius = 30
let fahrenheit = (celsius * 9/5) + 32
let kelvin = celsius + 273.15
console.log("Boa tarde! A temperatura atual é de:\n" + celsius + "°C")
console.log(fahrenheit + "°F" )
console.log(kelvin + "K" )
